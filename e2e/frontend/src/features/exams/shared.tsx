/** "Sat, 12 Sep 2026" */
export function fmtSlotDate(iso?: string | null) {
  if (!iso) return null;
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return null;
  return d.toLocaleDateString('en-IN', { weekday: 'short', day: 'numeric', month: 'short', year: 'numeric' });
}

/** "10:00 AM" */
export function fmtSlotTime(iso?: string | null) {
  if (!iso) return null;
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return null;
  return d.toLocaleTimeString('en-IN', { hour: 'numeric', minute: '2-digit' });
}

/** "Sat, 12 Sep 2026 · 10:00 AM" — the slot as the learner sees it. */
export function fmtSlot(iso?: string | null) {
  const date = fmtSlotDate(iso);
  return date ? `${date} · ${fmtSlotTime(iso)}` : null;
}

/**
 * "10:00 AM – 10:20 AM (20 min)" — the booked window, derived from the slot
 * length the admin allotted rather than assumed.
 */
export function slotWindow(iso?: string | null, minutes?: number | null) {
  const mins = minutes ?? DEFAULT_SLOT_MINUTES;
  const start = fmtSlotTime(iso);
  if (!start) return `${mins} min slot`;
  const end = fmtSlotTime(new Date(new Date(iso as string).getTime() + mins * 60_000).toISOString());
  return `${start} – ${end} (${mins} min)`;
}

/** Digits-only wa.me link; Indian numbers get the country code when missing. */
export function whatsappHref(number?: string | null) {
  if (!number) return null;
  const digits = number.replace(/\D/g, '');
  if (!digits) return null;
  return `https://wa.me/${digits.length === 10 ? `91${digits}` : digits}`;
}

/**
 * Examiner name + WhatsApp exactly as assigned by the admin. Renders a
 * placeholder rather than nothing while a slot is still awaiting assignment,
 * so the learner is never left wondering.
 */
export function ExaminerContact({
  examiner,
  compact,
}: {
  examiner: ExaminerContactFields;
  compact?: boolean;
}) {
  const wa = whatsappHref(examiner.examiner_whatsapp);
  if (!examiner.examiner_name) {
    return (
      <span className="inline-flex items-center gap-1.5 text-sm text-slate-400">
        <UserRound size={14} className="shrink-0" />
        Examiner to be assigned
      </span>
    );
  }
  return (
    <div className={compact ? 'flex flex-wrap items-center gap-x-3 gap-y-1' : 'space-y-1'}>
      <span className="inline-flex items-center gap-1.5 text-sm font-semibold text-slate-700">
        <UserRound size={14} className="shrink-0 text-brand" />
        {examiner.examiner_name}
      </span>
      {wa ? (
        <a
          href={wa}
          target="_blank"
          rel="noreferrer"
          className="inline-flex items-center gap-1.5 text-sm font-medium text-emerald-600 hover:text-emerald-700"
        >
          <MessageCircle size={14} className="shrink-0" />
          {examiner.examiner_whatsapp}
        </a>
      ) : examiner.examiner_phone ? (
        <a
          href={`tel:${examiner.examiner_phone}`}
          className="inline-flex items-center gap-1.5 text-sm text-slate-500 hover:text-brand"
        >
          <Phone size={14} className="shrink-0" />
          {examiner.examiner_phone}
        </a>
      ) : (
        <span className="text-xs text-slate-400">WhatsApp number not published yet</span>
      )}
    </div>
  );
}
