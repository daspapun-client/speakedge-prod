/** "Sunday – 11:00 AM" — the same label the API builds, for live previews. */
export function weeklySlotLabel(day: string, time: string) {
  const [h, m] = time.split(':').map(Number);
  if (Number.isNaN(h) || Number.isNaN(m)) return '';
  const suffix = h < 12 ? 'AM' : 'PM';
  return `${day.charAt(0).toUpperCase()}${day.slice(1)} \u2013 ${h % 12 || 12}:${String(m).padStart(2, '0')} ${suffix}`;
}

